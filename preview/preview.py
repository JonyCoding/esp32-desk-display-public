#!/usr/bin/env python3
"""Local 64x64 preview using the firmware renderer and native Adafruit GFX."""
from __future__ import annotations

import argparse
import json
import os
from pathlib import Path
import re
import shutil
import subprocess
import threading
import time
from http.server import BaseHTTPRequestHandler, ThreadingHTTPServer
from urllib.parse import urlparse
from urllib.request import ProxyHandler, Request, build_opener, urlopen
from urllib.error import HTTPError, URLError

ROOT = Path(__file__).resolve().parents[1]
PREVIEW = ROOT / 'preview'
LAN_OPENER = build_opener(ProxyHandler({}))
ESP32_REQUEST_LOCK = threading.Lock() # at most one forwarded request, no backlog
# Reset-to-defaults target for the /api/config UI. Keep in sync with the
# saved theme.json (this is the look the user tuned to on 2026-11-20).
DEFAULT_THEME = {
    'brightness': 70, 'nightColor': '#23396c', 'accentColor': '#ecad6f',
    'clockColor': '#ebebeb', 'quotaColor': '#56eaff', 'animationStepMs': 100,
    'sceneDetail': 5,
}
INT_LIMITS = {'brightness': (8, 160), 'animationStepMs': (40, 250), 'sceneDetail': (1, 5)}
MACROS = {'brightness': 'BRIGHTNESS', 'nightColor': 'NIGHT_COLOR', 'accentColor': 'ACCENT_COLOR',
          'clockColor': 'CLOCK_COLOR', 'quotaColor': 'QUOTA_COLOR', 'animationStepMs': 'ANIMATION_STEP_MS',
          'sceneDetail': 'SCENE_DETAIL'}


def validate_theme(value):
    if not isinstance(value, dict) or set(value) != set(DEFAULT_THEME):
        raise ValueError('theme fields do not match the supported settings')
    result = {}
    for key, item in value.items():
        if key in INT_LIMITS:
            low, high = INT_LIMITS[key]
            if type(item) is not int or not low <= item <= high:
                raise ValueError(f'{key} must be an integer from {low} to {high}')
            result[key] = item
        else:
            if not isinstance(item, str) or not re.fullmatch(r'#[0-9a-fA-F]{6}', item):
                raise ValueError(f'{key} must be a six digit hex color')
            result[key] = item.lower()
    return result


def theme_header(theme):
    theme = validate_theme(theme)
    lines = ['#pragma once', '// Generated by preview/preview.py when visual settings are saved.']
    for key, macro in MACROS.items():
        value = theme[key]
        literal = '0x' + value[1:] if isinstance(value, str) else str(value)
        lines.append(f'#define DESK_THEME_{macro} {literal}')
    return '\n'.join(lines) + '\n'


def build_renderer():
    libraries = Path(os.environ.get('ARDUINO_LIBRARIES', str(Path.home() / 'Documents/Arduino/libraries')))
    gfx = libraries / 'Adafruit_GFX_Library'
    arduino_json = libraries / 'ArduinoJson/src'
    compiler = shutil.which('clang++') or shutil.which('g++')
    if not compiler or not (gfx / 'Adafruit_GFX.cpp').exists() or not (arduino_json / 'ArduinoJson.h').exists():
        raise RuntimeError('Need a C++17 compiler, Adafruit GFX and ArduinoJson. Set ARDUINO_LIBRARIES to the Arduino libraries directory.')
    binary = ROOT / '.local/preview-renderer'
    if not binary.parent.exists(): binary.parent.mkdir(exist_ok=True)
    inputs = list((PREVIEW / 'host').glob('*.h')) + [PREVIEW / 'renderer.cpp', gfx / 'Adafruit_GFX.cpp', gfx / 'Adafruit_GFX.h', gfx / 'glcdfont.c', ROOT / 'firmware/desk_display/display_renderer.h', ROOT / 'firmware/desk_display/display_controller.h', Path(__file__)]
    if not binary.exists() or max(p.stat().st_mtime for p in inputs) > binary.stat().st_mtime:
        command = [compiler, '-std=c++17', '-O2', '-DARDUINO=10800',
                   '-DARDUINOJSON_ENABLE_ARDUINO_STRING=0', '-DARDUINOJSON_ENABLE_ARDUINO_STREAM=0',
                   '-DARDUINOJSON_ENABLE_ARDUINO_PRINT=0', '-DARDUINOJSON_ENABLE_PROGMEM=0',
                   '-I', str(PREVIEW / 'host'), '-I', str(ROOT / 'firmware/desk_display'),
                   '-I', str(gfx), '-I', str(arduino_json), str(PREVIEW / 'renderer.cpp'),
                   str(gfx / 'Adafruit_GFX.cpp'), '-o', str(binary)]
        subprocess.run(command, check=True)
    return binary


class Engine:
    def __init__(self):
        self.lock = threading.Lock()
        self.theme = validate_theme(json.loads((PREVIEW / 'theme.json').read_text()))
        self.previous = time.monotonic()
        self._spawn()

    def _spawn(self):
        # Hot-reload guard: recompile/respawn whenever firmware renderer
        # sources change, so the served frames always match the sources.
        self.binary = build_renderer()
        self.process = subprocess.Popen([str(self.binary)], stdin=subprocess.PIPE, stdout=subprocess.PIPE, text=True, bufsize=1)
        self.spawned_mtime = self.binary.stat().st_mtime

    def _maybe_refresh(self):
        try:
            binary = build_renderer()  # recompiles only when inputs are newer
        except Exception as exc:  # mid-edit compile error: keep last-good renderer
            print(f'preview: renderer rebuild skipped ({exc})', flush=True)
            return
        if binary.stat().st_mtime > self.spawned_mtime:
            self.close()
            self._spawn()

    def request(self, body=None):
        with self.lock:
            return self._request(body or {'op': 'frame'})

    def _request(self, body):
        self._maybe_refresh()
        now = time.monotonic()
        body = dict(body)
        body['delta_ms'] = min(int((now - self.previous) * 1000), 86400000)
        body['theme'] = self.theme
        self.previous = now
        self.process.stdin.write(json.dumps(body) + '\n'); self.process.stdin.flush()
        line = self.process.stdout.readline()
        if not line:
            raise RuntimeError('preview renderer stopped')
        result = json.loads(line)
        if 'error' in result:
            raise ValueError(result['error'])
        return result

    def change_theme(self, value, save=False):
        validated = validate_theme(value)
        with self.lock:
            if save:
                # Brightness is a runtime control, not a look. Saving it would
                # regenerate DESK_THEME_BRIGHTNESS in display_theme.h and turn
                # "I dimmed it once last night" into tomorrow's boot default —
                # the exact reason the panel kept coming up below 60. Keep the
                # level already on disk (edit theme.json by hand, then save, if
                # you really want a new compiled default).
                saved = dict(validated)
                try:
                    saved['brightness'] = validate_theme(
                        json.loads((PREVIEW / 'theme.json').read_text()))['brightness']
                except (OSError, ValueError):
                    saved['brightness'] = DEFAULT_THEME['brightness']
                # Both are project sources; firmware consumes the generated header.
                paths = [(PREVIEW / 'theme.json', json.dumps(saved, indent=2) + '\n'),
                         (ROOT / 'firmware/desk_display/display_theme.h', theme_header(saved))]
                for path, contents in paths:
                    temp = path.with_suffix(path.suffix + '.tmp')
                    temp.write_text(contents); temp.replace(path)
            self.theme = validated
            return self._request({'op': 'frame'})

    def close(self):
        self.process.terminate()
        try: self.process.wait(timeout=2)
        except subprocess.TimeoutExpired: self.process.kill(); self.process.wait()


class DeviceError(RuntimeError):
    pass


class DeviceClient:
    """The loopback preview proxies approved commands; tokens never reach JS."""
    def __init__(self, url='http://127.0.0.1:8765', token_file=None):
        self.url = url.rstrip('/')
        self.token_file = token_file or ROOT / '.local/token'

    def request(self, path='/state', body=None):
        try:
            token = os.environ.get('DESKDISPLAY_TOKEN') or self.token_file.read_text().strip()
            request = Request(self.url + path, data=json.dumps(body).encode() if body is not None else None,
                              headers={'Authorization': 'Bearer ' + token, 'Content-Type': 'application/json'})
            with urlopen(request, timeout=3) as response:
                return json.load(response)
        except HTTPError as exc:
            if exc.code == 401:
                raise DeviceError('Mac 数据服务的凭据不匹配，请检查本机 token 配置') from exc
            raise DeviceError(f'Mac 数据服务拒绝指令（{exc.code}）') from exc
        except (OSError, ValueError, URLError) as exc:
            raise DeviceError('无法连接 Mac 数据服务，请检查本机 8765 服务是否运行') from exc

    def control(self, body):
        if set(body) != {'op', 'value'}:
            raise ValueError('指令需要 op 和 value')
        op, value = body['op'], body['value']
        if op == 'page' and isinstance(value, str) and value in ('quota', 'clock', 'loft', 'status', 'stock'):
            return self.request('/page', {'page': value})
        if op == 'button' and type(value) is int and 0 <= value <= 2:
            return self.request('/button', {'action': ('short', 'long', 'double')[value]})
        if op == 'brightness' and type(value) is int and 8 <= value <= 160:
            return self.request('/display', {'brightness': value})
        if op == 'resume' and value is True:
            return self.request('/resume', {})
        raise ValueError('不支持的真机指令')


class Handler(BaseHTTPRequestHandler):
    def local_request(self):
        port = self.server.server_port
        allowed = {f'127.0.0.1:{port}', f'localhost:{port}'}
        if self.headers.get('Host') not in allowed:
            self.send(403, {'error': 'local host required'}); return False
        origin = self.headers.get('Origin')
        if origin and origin not in {f'http://{host}' for host in allowed}:
            self.send(403, {'error': 'same origin required'}); return False
        return True

    def log_message(self, fmt, *args):
        if args and str(args[1] if len(args) > 1 else '') != '200':
            super().log_message(fmt, *args)

    def send(self, code, body, content_type='application/json; charset=utf-8'):
        if not isinstance(body, bytes): body = json.dumps(body, ensure_ascii=False).encode()
        self.send_response(code)
        self.send_header('Content-Type', content_type)
        self.send_header('Content-Length', str(len(body)))
        self.send_header('Cache-Control', 'no-store')
        self.end_headers()
        try: self.wfile.write(body)
        except (BrokenPipeError, ConnectionResetError): pass

    def do_GET(self):
        if not self.local_request(): return
        path = urlparse(self.path).path
        try:
            if path == '/api/frame': self.send(200, self.server.engine.request())
            elif path == '/api/config': self.send(200, {'theme': self.server.engine.theme, 'defaults': DEFAULT_THEME})
            elif path == '/api/health': self.send(200, {'ok': True, 'renderer': 'shared-firmware-adafruit-gfx'})
            elif path == '/api/device': self.send(200, self.server.device.request())
            elif path.startswith('/api/esp32/'):
                sub = path[len('/api/esp32/'):]
                qs = urlparse(self.path).query
                host_file = ROOT / '.local/esp32-host'
                host = os.environ.get('DESK_ESP32_HOST') or (host_file.read_text().strip() if host_file.exists() else '')
                if not host:
                    self.send(503, {'error': '请先在 .local/esp32-host 设置设备地址', 'connected': False})
                    return
                target = f'http://{host}/{sub}' + (f'?{qs}' if qs else '')
                if not ESP32_REQUEST_LOCK.acquire(blocking=False):
                    self.send(503, {'error': 'ESP32 正忙，请稍后重试', 'busy': True})
                    return
                try:
                    req = Request(target)
                    timeout = 5.0 if sub == 'api/status' else 1.0 if sub == 'brightness' else 2.5
                    with LAN_OPENER.open(req, timeout=timeout) as resp:
                        mime = resp.headers.get('Content-Type', 'application/json; charset=utf-8')
                        self.send(200, resp.read(), content_type=mime)
                except HTTPError as exc:
                    if exc.code == 409 and sub in ('page', 'carousel'):
                        self.send(409, {'error': 'Mac session is locked'})
                    else:
                        self.send(502, {'error': f'ESP32 请求失败: {exc}', 'connected': False})
                except Exception as exc:
                    self.send(502, {'error': f'ESP32 请求失败: {exc}', 'connected': False})
                finally:
                    ESP32_REQUEST_LOCK.release()
            elif path in ('/', '/app.js', '/style.css'):
                name, mime = {'/': ('index.html', 'text/html; charset=utf-8'),
                              '/app.js': ('app.js', 'text/javascript; charset=utf-8'),
                              '/style.css': ('style.css', 'text/css; charset=utf-8')}[path]
                self.send(200, (PREVIEW / name).read_bytes(), mime)
            else: self.send(404, {'error': 'not found'})
        except DeviceError as exc: self.send(502, {'error': str(exc)})
        except Exception as exc:
            self.send(500, {'error': str(exc)})

    def do_POST(self):
        try:
            if not self.local_request(): return
            if self.headers.get_content_type() != 'application/json':
                raise ValueError('JSON body required')
            length = int(self.headers.get('Content-Length', '0'))
            if not 0 < length <= 4096: raise ValueError('invalid body size')
            self.connection.settimeout(5)
            body = json.loads(self.rfile.read(length))
            if not isinstance(body, dict): raise ValueError('JSON object required')
            path = urlparse(self.path).path
            if path in ('/api/theme', '/api/save'):
                self.send(200, self.server.engine.change_theme(body, save=path == '/api/save'))
            elif path == '/api/action':
                validate_action(body)
                self.send(200, self.server.engine.request(body))
            elif path == '/api/device':
                self.send(200, self.server.device.control(body))
            else: self.send(404, {'error': 'not found'})
        except (ValueError, TypeError) as exc: self.send(400, {'error': str(exc)})
        except DeviceError as exc: self.send(502, {'error': str(exc)})
        except Exception as exc: self.send(500, {'error': str(exc)})


def validate_action(body):
    op = body.get('op')
    enums = {'preset': ('work', 'afterhours', 'offline', 'manual', 'low', 'stale', 'noquota', 'cold', 'schedule', 'nightclock', 'status'),
             'page': ('loft', 'quota', 'clock', 'status', 'stock'), 'mac': ('disconnect', 'lock', 'wake')}
    if op in enums:
        if not isinstance(body.get('value'), str) or body['value'] not in enums[op]: raise ValueError('invalid action value')
    elif op == 'scene':
        if type(body.get('value')) is not int or not -1 <= body['value'] <= 7:
            raise ValueError('scene must be -1..7')
    elif op in ('night', 'motion'):
        high = 2 if op == 'night' else 6  # five faces + the relief, see GestureMood
        if type(body.get('value')) is not int or not 0 <= body['value'] <= high: raise ValueError('invalid action value')
    elif op in ('button', 'skip'):
        low, high = (0, 2) if op == 'button' else (0, 86400000)
        if type(body.get('value')) is not int or not low <= body['value'] <= high: raise ValueError('invalid action value')
    elif op == 'pause':
        if type(body.get('value')) is not bool: raise ValueError('boolean required')
    elif op == 'ink':
        value = body.get('value')
        if value not in ('theme', 'auto', 'next') and (
                not isinstance(value, str) or not re.fullmatch(r'#[0-9a-fA-F]{6}', value)):
            raise ValueError('ink must be "theme", "auto", "next" or a six digit hex colour')
    elif op == 'values':
        ranges = {'quota5h': (-1, 100), 'quotaWeek': (-1, 100), 'ageMinutes': (0, 10080), 'resetMinutes': (0, 10080), 'reset5hAt': (0, 4102444799), 'epoch': (1700000000, 4102444799),
                  'rssi': (-120, 0), 'heapKb': (0, 4096), 'clockSrc': (0, 2), 'httpCode': (-1, 599),
                  'mpuPose': (0, 5), 'tiltDeg': (0, 180)}
        for key, value in body.items():
            if key == 'op': continue
            if key == 'stock':
                if not isinstance(value, dict): raise ValueError('stock must be a dict')
                continue
            if key in ('wifi', 'mpu'):
                if not isinstance(value, bool): raise ValueError(f'{key} must be a boolean')
                continue
            if key == 'ip':
                if not isinstance(value, str) or not re.fullmatch(r'[0-9A-Za-z.:-]{0,15}', value): raise ValueError('invalid ip address')
                continue
            if key == 'message':
                if not isinstance(value, str) or len(value) > 160 or any(ord(c) < 32 or ord(c) > 126 for c in value): raise ValueError('message must be printable ASCII, up to 160 characters')
            elif key not in ranges or type(value) is not int or not ranges[key][0] <= value <= ranges[key][1]: raise ValueError('invalid simulated data')
    else: raise ValueError('invalid action')


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--port', type=int, default=8766)
    parser.add_argument('--build-only', action='store_true')
    args = parser.parse_args()
    if args.build_only:
        print(build_renderer()); return
    engine = Engine()
    try:
        server = ThreadingHTTPServer(('127.0.0.1', args.port), Handler)
        server.engine = engine
        server.device = DeviceClient()
        print(f'Desk Display Preview: http://127.0.0.1:{server.server_port}', flush=True)
        server.serve_forever()
    except KeyboardInterrupt:
        pass
    finally:
        engine.close()


if __name__ == '__main__': main()
